"""
Builds results/baseline_t6.json: T6's OWN frozen acceptance baseline.

Distinct from results/pilot.json on purpose -- pilot.json was frozen before
P2/P3 were removed (T3) and before the UNWIRED return-statement fix, so its
corpus composition doesn't match what the gate actually ships against.
pilot.json stays untouched as historical reference; this file is T6's.

Run this once per corpus/detector change that's meant to move T6's
baseline (`make gate-baseline`). Do NOT run it to chase the number up --
same discipline as `make pilot` for pilot.json (CLAUDE.md: do not edit
frozen baselines to move goalposts).
"""

from __future__ import annotations

import json
import sys
from collections import defaultdict

sys.path.insert(0, ".")

from scripts.analyze import boot_indices, load, metrics

THRESHOLD = 0.80


def build() -> dict:
    recs = load()
    per: dict[str, list] = defaultdict(list)
    for r in recs:
        if r["detector"] == "P1 defined":
            per[r["iid"]].append((r["pred"], r["gold"]))
    iids = sorted(per)

    m = metrics([x for i in iids for x in per[i]])
    B = boot_indices(iids, 1000, 0)
    vals = sorted(
        metrics([x for i in samp for x in per[i]])["precision"] for samp in B
    )
    lo, hi = vals[25], vals[974]

    return {
        "frozen_at": "T6 baseline, post-T3 (P2/P3 removed) / post-UNWIRED-fix corpus",
        "n_instances": len(iids),
        "detector": "P1 defined",
        "precision": m["precision"],
        "precision_ci95": [lo, hi],
        "acceptance_threshold": THRESHOLD,
        "note": (
            f"Precision sits within noise of the {THRESHOLD} threshold: "
            f"point estimate {m['precision']:.4f}, 95% CI [{lo:.4f}, "
            f"{hi:.4f}] (cluster bootstrap over instances, same method as "
            f"scripts/analyze.py). This is NOT a comfortable margin -- see "
            f"ASSUMPTIONS.md's T6 section. Do not edit this file by hand; "
            f"regenerate via `make gate-baseline`."
        ),
    }


def main() -> None:
    out = build()
    with open("results/baseline_t6.json", "w") as f:
        json.dump(out, f, indent=2)
        f.write("\n")
    print(json.dumps(out, indent=2))


if __name__ == "__main__":
    main()
